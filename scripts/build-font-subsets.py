"""Build the site's Chinese webfonts from the checked-in Noto Sans SC sources."""

from collections import defaultdict
from io import BytesIO
from pathlib import Path
import json

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
EXTENDED = FONTS / "noto-sans-sc-extended.woff2"


def unicode_range(points):
    ranges = []
    start = end = points[0]
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
            start = end = point
    ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ",".join(ranges)


def font_face(filename, points):
    return (
        "@font-face {\n"
        "  font-family: 'Noto Sans SC';\n"
        "  font-style: normal;\n"
        "  font-weight: 100 900;\n"
        "  font-display: swap;\n"
        f"  src: url('{filename}') format('woff2');\n"
        f"  unicode-range: {unicode_range(sorted(points))};\n"
        "}\n"
    )


def save_subset(filename, points, source):
    options = subset.Options()
    options.name_IDs = ["*"]
    options.layout_features = ["*"]
    with TTFont(BytesIO(source), recalcTimestamp=False) as font:
        font.flavor = "woff2"
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        font.save(FONTS / filename)
    size = (FONTS / filename).stat().st_size
    print(f"{filename}: {len(points)} characters, {size:,} bytes", flush=True)
    return font_face(filename, points)


def build():
    with TTFont(FONTS / "noto-sans-sc-ui.woff2") as font:
        common = {point for point in font.getBestCmap() if point >= 0x2000}
    with TTFont(EXTENDED) as font:
        extended = {point for point in font.getBestCmap() if point >= 0x2000} - common
        font.flavor = None
        font.recalcTimestamp = False
        buffer = BytesIO()
        font.save(buffer)
        source = buffer.getvalue()
    print("Decoded source font once; generating WOFF2 subsets.", flush=True)

    files = [ROOT / "catalog.json", ROOT / "index.html", ROOT / "prompts.html"]
    files += sorted((ROOT / "src").rglob("*.tsx"))
    files += sorted((ROOT / "prompts").rglob("*.md"))
    texts = []
    for path in files:
        text = path.read_text(encoding="utf-8")
        if path.suffix == ".json":
            text = json.dumps(json.loads(text), ensure_ascii=False)
        texts.append(text)
    content = {ord(char) for char in "\n".join(texts)} & extended

    css = [
        "/* Generated by scripts/build-font-subsets.py. Chinese and full-width\n"
        "   characters use Noto Sans SC; Latin stays in the system fonts. */\n",
        font_face("noto-sans-sc-ui.woff2", common),
        save_subset("noto-sans-sc-content.woff2", content, source),
    ]
    blocks = defaultdict(set)
    for point in extended - content:
        blocks[point // 0x800].add(point)
    for block, points in sorted(blocks.items()):
        css.append(save_subset(f"noto-sans-sc-block-{block:03x}.woff2", points, source))
    (FONTS / "chinese.css").write_text("\n".join(css), encoding="utf-8", newline="\n")
    print(f"Built content subset and {len(blocks)} Unicode blocks; kept variable weights and hinting.")


if __name__ == "__main__":
    build()
